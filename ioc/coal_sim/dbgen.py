"""The EPICS .db file and the CSV inventory for the monitoring application, both written from plant.build()."""
import csv

# EGU as written in the .db is plain ASCII (as in the HVAC database); the CSV uses the Unit Catalog symbol.
CATALOG_UNIT = {"degC": "°C", "um": "µm", "m3/hr": "m³/hr", "m3": "m³"}
SEVERITY_FIELDS = (("HIHI", "HHSV", "MAJOR"), ("HIGH", "HSV", "MINOR"), ("LOW", "LSV", "MINOR"), ("LOLO", "LLSV", "MAJOR"))


def _num(v, prec):
    return ("%.*f" % (prec + 1, v)).rstrip("0").rstrip(".") if prec else "%d" % round(v)


def db_text(plant):
    out = ["# Coal power plant softIOC database (one 300 MW pulverised-coal unit)",
           "# Generated by: python -m coal_sim generate-db   -- do not edit by hand, change coal_sim/plant.py instead.",
           "# Simulation only: no hardware or device support. The simulator (coal_sim) writes each VAL over Channel Access.",
           ""]
    for p in plant.points:
        out.append('record(%s, "%s") {' % (p.rtype, p.name))
        out.append('    field(DESC, "%s")' % p.desc)
        if p.rtype == "ai":
            if p.egu:
                out.append('    field(EGU, "%s")' % p.egu)
            out.append('    field(PREC, "%d")' % p.prec)
            out.append('    field(VAL, "%s")' % _num(p.initial, p.prec))
            out.append('    field(LOPR, "%s")' % _num(p.lopr, p.prec))
            out.append('    field(HOPR, "%s")' % _num(p.hopr, p.prec))
            for key, sev_field, sev in SEVERITY_FIELDS:
                if key in p.lim:
                    out.append('    field(%s, "%s")' % (key, _num(p.lim[key], p.prec)))
                    out.append('    field(%s, "%s")' % (sev_field, sev))
            out.append('    field(HYST, "%s")' % _num(p.hyst, p.prec))
        else:
            out.append('    field(ZNAM, "%s")' % p.znam)
            out.append('    field(ONAM, "%s")' % p.onam)
            out.append('    field(VAL, "%d")' % p.value0)
            out.append('    field(ZSV, "%s")' % p.zsv)
            out.append('    field(OSV, "%s")' % p.osv)
        out.append("}")
    return "\n".join(out) + "\n"


def write_db(plant, path):
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(db_text(plant))


def write_inventory(plant, path, stale_after=30):
    """CSV in the column layout of the monitoring application's PV import (same as the HVAC inventory)."""
    with open(path, "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["epics_pv_name", "pv_name", "system", "equipment", "description", "unit", "record_type", "display_low", "display_high",
                    "state0", "state1", "history_deadband", "stale_after_s"])
        for p in plant.points:
            analog = p.rtype == "ai"
            w.writerow([p.name, p.name, p.system, plant.equips[p.equip].label, p.desc, CATALOG_UNIT.get(p.egu, p.egu), p.rtype,
                        p.lopr if analog else "", p.hopr if analog else "",
                        "" if analog else p.znam, "" if analog else p.onam, "", stale_after if analog else ""])
