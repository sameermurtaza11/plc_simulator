#!/usr/bin/env python3
"""Generate a large EPICS test database (default 3000 records) for load tests.

Produces three files in --out-dir:

  load_<N>.db         EPICS records (load with softIoc, see README.md)
  load_<N>_pvs.csv    the PV inventory in the form the monitoring app will import
                      (pv_name, system, equipment, description, unit, kind)
  load_<N>_expected.json
                      what the IOC was configured to expose: units, display range, alarm
                      limits and severities per PV. The acceptance tests compare what the
                      Channel Access adapter reads against this file.

The records are the same families as test_small.db (calc waveforms driven by one shared
counter, bi/mbbi for binary and enum signals). The generated file defines its own counter, so
load it instead of test_small.db, not together with it. Everything is deterministic for a given
--seed, so a failed run can be reproduced.

The distribution is controlled by options, because the real update rates are unknown:

  --scan-mix   fraction of analog records per scan class, "fast:normal:slow"
               (.1 s : 1 s : 10 s), default 0.05:0.75:0.20
  --digital    fraction of records that are bi/mbbi (default 0.15)
  --nolimits   fraction of analog records without any alarm limit (default 0.10)
  --mdel       monitor deadband for analog records as a fraction of their span (default 0.002)

This script only writes files. It never talks to an IOC.
"""
import argparse
import csv
import json
import math
import os
import random

SYSTEMS = ["Compressed air", "Cooling water", "Steam", "Boiler house", "Pumping", "Ventilation", "Power", "Fuel"]
EQUIP_PREFIX = {"Compressed air": "K", "Cooling water": "CW", "Steam": "SG", "Boiler house": "B",
                "Pumping": "P", "Ventilation": "AHU", "Power": "TR", "Fuel": "T"}
ANALOG = [  # (label, unit, lo, hi, prec)
    ("PRESSURE", "bar", 0, 16, 2), ("TEMPERATURE", "degC", 0, 150, 1), ("FLOW", "m3/h", 0, 500, 1),
    ("LEVEL", "%", 0, 100, 1), ("CURRENT", "A", 0, 200, 1), ("POWER", "kW", 0, 2000, 0),
    ("SPEED", "rpm", 0, 3000, 0), ("VIBRATION", "mm/s", 0, 20, 2),
]
SCAN = {"fast": ".1 second", "normal": "1 second", "slow": "10 second"}


def fnum(x):
    return ("%.6g" % x)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--count", type=int, default=3000, help="number of PVs (records), default 3000")
    ap.add_argument("--prefix", default="LOAD:", help="PV name prefix, default LOAD:")
    ap.add_argument("--out-dir", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "generated"))
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--scan-mix", default="0.05:0.75:0.20")
    ap.add_argument("--digital", type=float, default=0.15)
    ap.add_argument("--nolimits", type=float, default=0.10)
    ap.add_argument("--mdel", type=float, default=0.002)
    a = ap.parse_args()

    mix = [float(x) for x in a.scan_mix.split(":")]
    if len(mix) != 3 or abs(sum(mix) - 1) > 1e-6:
        ap.error("--scan-mix needs three fractions that add up to 1, e.g. 0.05:0.75:0.20")
    rng = random.Random(a.seed)
    os.makedirs(a.out_dir, exist_ok=True)
    base = os.path.join(a.out_dir, "load_%d" % a.count)

    db, rows, expected = [], [], {}
    db.append("# Generated by generate_db.py (count=%d seed=%d). Do not edit; regenerate." % (a.count, a.seed))
    db.append("# Self-contained: defines its own shared counter $(P)tick. Load it INSTEAD OF test_small.db")
    db.append("# (both define $(P)tick), with:  softIoc -m P=%s -d load_%d.db" % (a.prefix, a.count))
    db.append("")
    db.append('record(calc, "$(P)tick") {')
    db.append('    field(DESC, "shared test counter, degrees")')
    db.append('    field(SCAN, "1 second")')
    db.append('    field(INPA, "$(P)tick.VAL")')
    db.append('    field(CALC, "(A>=354)?0:A+6")')
    db.append("}")
    db.append("")

    for i in range(1, a.count + 1):
        system = SYSTEMS[(i - 1) % len(SYSTEMS)]
        equip = "%s-%03d" % (EQUIP_PREFIX[system], (i - 1) // len(SYSTEMS) % 60 + 1)
        digital = rng.random() < a.digital
        if digital:
            name = "%s%s:%s%04d" % (a.prefix, equip, "STS", i)
            enum = rng.random() < 0.25
            phase = rng.randrange(0, 360, 6)
            if enum:
                src = name + "_src"
                db.append('record(calc, "%s") {' % src)
                db.append('    field(SCAN, "1 second")')
                db.append('    field(INPA, "$(P)tick NPP")')
                db.append('    field(CALC, "FLOOR(MOD(A+%d,360)/90)")' % phase)
                db.append("}")
                db.append('record(mbbi, "%s") {' % name)
                db.append('    field(DESC, "%s mode %d")' % (equip, i))
                db.append('    field(SCAN, "1 second")')
                db.append('    field(INP,  "%s NPP")' % src)
                db.append('    field(NOBT, "2")')
                for k, (nm, st, sv) in enumerate([("ZR", "OFF", "NO_ALARM"), ("ON", "STANDBY", "NO_ALARM"),
                                                  ("TW", "RUN", "NO_ALARM"), ("TH", "FAULT", "MAJOR")]):
                    db.append('    field(%sVL, "%d")' % (nm, k))
                    db.append('    field(%sST, "%s")' % (nm, st))
                    db.append('    field(%sSV, "%s")' % (nm, sv))
                db.append("}")
                kind = "enum"
                expected[name] = {"kind": "enum", "rtyp": "mbbi", "states": ["OFF", "STANDBY", "RUN", "FAULT"],
                                  "severities": ["NO_ALARM", "NO_ALARM", "NO_ALARM", "MAJOR"], "scan": "1 second"}
            else:
                src = name + "_src"
                duty = rng.choice([90, 180, 270, 330])
                db.append('record(calc, "%s") {' % src)
                db.append('    field(SCAN, "1 second")')
                db.append('    field(INPA, "$(P)tick NPP")')
                db.append('    field(CALC, "MOD(A+%d,360)<%d")' % (phase, duty))
                db.append("}")
                on_bad = rng.random() < 0.5  # which state raises the alarm
                db.append('record(bi, "%s") {' % name)
                db.append('    field(DESC, "%s status %d")' % (equip, i))
                db.append('    field(SCAN, "1 second")')
                db.append('    field(INP,  "%s NPP")' % src)
                db.append('    field(ZNAM, "%s")' % ("OK" if on_bad else "STOPPED"))
                db.append('    field(ONAM, "%s")' % ("TRIPPED" if on_bad else "RUNNING"))
                db.append('    field(ZSV,  "%s")' % ("NO_ALARM" if on_bad else "MAJOR"))
                db.append('    field(OSV,  "%s")' % ("MAJOR" if on_bad else "NO_ALARM"))
                db.append("}")
                kind = "binary"
                expected[name] = {"kind": "binary", "rtyp": "bi",
                                  "states": ["OK", "TRIPPED"] if on_bad else ["STOPPED", "RUNNING"],
                                  "severities": ["NO_ALARM", "MAJOR"] if on_bad else ["MAJOR", "NO_ALARM"], "scan": "1 second"}
            rows.append([name, system, equip, "%s status %d" % (equip, i), "", kind])
            continue

        label, unit, lo, hi, prec = ANALOG[rng.randrange(len(ANALOG))]
        name = "%s%s:%s%04d" % (a.prefix, equip, label[:3], i)
        scan_cls = rng.choices(["fast", "normal", "slow"], weights=mix)[0]
        span = hi - lo
        mid = lo + span * rng.uniform(0.35, 0.65)
        amp = span * rng.uniform(0.15, 0.40)
        phase = rng.randrange(0, 360, 6)
        limits = rng.random() >= a.nolimits
        db.append('record(calc, "%s") {' % name)
        db.append('    field(DESC, "%s %s %d")' % (equip, label.lower(), i))
        db.append('    field(SCAN, "%s")' % SCAN[scan_cls])
        db.append('    field(INPA, "$(P)tick NPP")')
        db.append('    field(CALC, "%s+%s*SIN((A+%d)*PI/180)")' % (fnum(mid), fnum(amp), phase))
        db.append('    field(EGU,  "%s")' % unit)
        db.append('    field(PREC, "%d")' % prec)
        db.append('    field(HOPR, "%s")' % fnum(hi))
        db.append('    field(LOPR, "%s")' % fnum(lo))
        db.append('    field(MDEL, "%s")' % fnum(span * a.mdel))
        exp = {"kind": "analog", "rtyp": "calc", "egu": unit, "prec": prec, "hopr": hi, "lopr": lo,
               "mdel": span * a.mdel, "scan": SCAN[scan_cls], "limits": None}
        if limits:
            # inner limits inside the swing so alarms occur, outer ones near its extremes
            hihi, high = mid + amp * 0.95, mid + amp * 0.70
            low, lolo = mid - amp * 0.70, mid - amp * 0.95
            hyst = span * 0.01
            for f, v in (("HIHI", hihi), ("HIGH", high), ("LOW", low), ("LOLO", lolo), ("HYST", hyst)):
                db.append('    field(%s, "%s")' % (f, fnum(v)))
            for f, v in (("HHSV", "MAJOR"), ("HSV", "MINOR"), ("LSV", "MINOR"), ("LLSV", "MAJOR")):
                db.append('    field(%s, "%s")' % (f, v))
            exp["limits"] = {"hihi": float("%.6g" % hihi), "high": float("%.6g" % high), "low": float("%.6g" % low),
                             "lolo": float("%.6g" % lolo), "hyst": float("%.6g" % hyst),
                             "hhsv": "MAJOR", "hsv": "MINOR", "lsv": "MINOR", "llsv": "MAJOR"}
        db.append("}")
        expected[name] = exp
        rows.append([name, system, equip, "%s %s %d" % (equip, label.lower(), i), unit, "analog"])

    with open(base + ".db", "w", newline="\n") as f:
        f.write("\n".join(db) + "\n")
    with open(base + "_pvs.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["pv_name", "system", "equipment", "description", "unit", "kind"])
        w.writerows(rows)
    with open(base + "_expected.json", "w", encoding="utf-8") as f:
        json.dump(expected, f, indent=1, sort_keys=True)

    n_dig = sum(1 for r in rows if r[5] != "analog")
    n_fast = sum(1 for v in expected.values() if v.get("scan") == SCAN["fast"])
    n_slow = sum(1 for v in expected.values() if v.get("scan") == SCAN["slow"])
    # worst-case update load if every scan posts a monitor (no deadband help)
    rate = sum({".1 second": 10.0, "1 second": 1.0, "10 second": 0.1}[v["scan"]] for v in expected.values())
    print("wrote %s.{db,_pvs.csv,_expected.json}" % base)
    print("  %d records: %d analog, %d binary/enum; scan .1s=%d 10s=%d" % (a.count, a.count - n_dig, n_dig, n_fast, n_slow))
    print("  upper bound of monitor events/s (every scan posts): %.0f" % rate)


if __name__ == "__main__":
    main()
